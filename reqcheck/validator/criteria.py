def name_ru(key: str) -> str:
    return CRITERIA.get(key, (key,))[0]


def standard_ref(key: str) -> str:
    return CRITERIA[key][1] if key in CRITERIA else ""


def criteria_block(keys=None) -> str:
    keys = keys or list(CRITERIA)
    return "\n".join(f"- {k} — {CRITERIA[k][0]}: {CRITERIA[k][2]}" for k in keys)
